from django.contrib import admin
from django.urls import path, include

from rest_framework import permissions
from drf_yasg.views import get_schema_view
from drf_yasg import openapi

schema_view = get_schema_view(
   openapi.Info(
      title="Fundraiser Platform",
      default_version='v1.0',
      description="A Django backend for a fundraising platform, enabling users to create campaigns, donate to causes, and manage funds securely.",
      terms_of_service="https://www.google.com/policies/terms/",
      contact=openapi.Contact(email="info@msaadafund.com"),
      license=openapi.License(name="MIT License"),
   ),
   public=True,
   permission_classes=(permissions.AllowAny,),
)

urlpatterns = [
    path('admin/', admin.site.urls),
    path('api/v1.0/', include("profiles.urls")),

    path('o/', include('oauth2_provider.urls', namespace='oauth2_provider')),

    path('swagger/', schema_view.with_ui('swagger', cache_timeout=0), name='schema-swagger-ui'),
    path('redoc/', schema_view.with_ui('redoc', cache_timeout=0), name='schema-redoc'),
    path('swagger.json', schema_view.without_ui(cache_timeout=0), name='schema-json'),
    
]